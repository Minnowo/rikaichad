"""Writes the licenses of the third-party crates compiled into the rikaichad
binary (normal dependencies of the `rikaichad` package, for the host
platform), for distribution with binaries.

For each crate: name, version, SPDX license, and the license files the
crate ships (LICENSE*, COPYING*, NOTICE*), each file once per crate.
Bundled C libraries are covered by their crates' files (SQLite is public
domain; zstd ships its BSD license with zstd-sys). Exits 1 if a crate
ships no license file, so a new dependency without one is noticed.

Usage: python3 -I scripts/third-party-licenses.py > THIRD-PARTY-LICENSES.txt
"""

import json
import os
import subprocess
import sys

LICENSE_PREFIXES = ("license", "licence", "copying", "notice")


def main() -> int:
    metadata = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--filter-platform",
             host_triple()],
            check=True, capture_output=True, text=True,
        ).stdout
    )
    packages = {p["id"]: p for p in metadata["packages"]}
    workspace = set(metadata["workspace_members"])
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
    root = next(i for i in workspace if packages[i]["name"] == "rikaichad")

    # Normal (not dev) dependencies, transitively; build dependencies are
    # not in the binary.
    seen, stack = set(), [root]
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if None in kinds and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    crates = sorted(
        (packages[i] for i in seen if i not in workspace),
        key=lambda p: (p["name"], p["version"]),
    )

    out = sys.stdout
    out.write("Third-party software in the rikaichad binary\n")
    out.write("=========================================\n\n")
    out.write("Generated by scripts/third-party-licenses.py from Cargo.lock.\n")
    out.write("rikaichad's own license and the Yomitan-derived parts are in LICENSE\n")
    out.write("and NOTICE.\n\n")
    missing = []
    for crate in crates:
        directory = os.path.dirname(crate["manifest_path"])
        files = sorted(
            f for f in os.listdir(directory)
            if f.lower().startswith(LICENSE_PREFIXES) and os.path.isfile(os.path.join(directory, f))
        )
        out.write("-" * 72 + "\n")
        out.write(f"{crate['name']} {crate['version']}\n")
        out.write(f"License: {crate.get('license') or 'see files'}\n")
        if crate.get("repository"):
            out.write(f"Source: {crate['repository']}\n")
        out.write("\n")
        if not files:
            missing.append(crate["name"])
        for name in files:
            with open(os.path.join(directory, name), encoding="utf-8", errors="replace") as f:
                text = f.read().strip()
            out.write(f"--- {name} ---\n\n{text}\n\n")
    if missing:
        print("crates without license files: " + ", ".join(missing), file=sys.stderr)
        return 1
    return 0


def host_triple() -> str:
    output = subprocess.run(["rustc", "-vV"], check=True, capture_output=True, text=True).stdout
    for line in output.splitlines():
        if line.startswith("host: "):
            return line.split(": ", 1)[1]
    raise SystemExit("cannot find the host triple")


if __name__ == "__main__":
    sys.exit(main())
